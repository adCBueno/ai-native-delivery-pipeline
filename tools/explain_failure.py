"""AI failure explainer for GitLab CI.

Runs in the last stage of a pipeline when an earlier job failed. It:
  1. finds the failed jobs in the current pipeline,
  2. downloads the end of each job log (that is where errors usually are),
  3. removes secrets and noise before anything leaves GitLab,
  4. asks an LLM for the likely root cause and a suggested fix,
  5. posts the answer as a merge request comment and saves it as an artifact.

Environment (most are provided by GitLab automatically):
  CI_API_V4_URL, CI_PROJECT_ID, CI_PIPELINE_ID, CI_MERGE_REQUEST_IID (optional)
  GITLAB_API_TOKEN   project access token with the `api` scope (masked CI variable)
  ANTHROPIC_API_KEY  masked CI variable; without it the script does a dry run
  AI_MODEL           optional, defaults to DEFAULT_MODEL
  MAX_LOG_CHARS      optional, characters kept from the end of each log
"""

from __future__ import annotations

import os
import re
import sys
from dataclasses import dataclass

import requests

DEFAULT_MODEL = "claude-sonnet-5-5"
ANTHROPIC_URL = "https://api.anthropic.com/v1/messages"
REPORT_FILE = "ai-failure-report.md"
NOTE_HEADER = "### AI summary of the pipeline failure"
DISCLAIMER = "_Generated by an LLM from the job logs. Check it before acting on it._"

ANSI_RE = re.compile(r"\x1b\[[0-9;?]*[A-Za-z]")
SECTION_RE = re.compile(r"section_(start|end):\d+:[A-Za-z0-9_.\-]+(\[[^\]]*\])?\r?")

# Patterns for well-known secret formats. Values of secret-looking
# environment variables are also removed (see redact()).
SECRET_PATTERNS = [
    re.compile(r"glpat-[A-Za-z0-9_\-]{20,}"),  # GitLab personal/project tokens
    re.compile(r"sk-ant-[A-Za-z0-9_\-]{20,}"),  # Anthropic keys
    re.compile(r"sk-[A-Za-z0-9]{32,}"),  # OpenAI-style keys
    re.compile(r"AKIA[0-9A-Z]{16}"),  # AWS access key ids
    re.compile(r"gh[pousr]_[A-Za-z0-9]{36,}"),  # GitHub tokens
    re.compile(r"(?i)(bearer\s+)[A-Za-z0-9._\-]{16,}"),
    re.compile(r"(?i)((?:password|passwd|secret|token|api[_-]?key)\s*[=:]\s*)\S+"),
    re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----[\s\S]+?-----END [A-Z ]*PRIVATE KEY-----"),
]
SECRET_ENV_NAME = re.compile(r"(TOKEN|SECRET|PASSWORD|PASSWD|API_KEY|PRIVATE_KEY)", re.I)


@dataclass
class FailedJob:
    id: int
    name: str
    stage: str
    web_url: str
    log: str = ""


# ------------------------------------------------------------ pure helpers


def clean_log(raw: str) -> str:
    """Remove colour codes and GitLab's collapsible-section markers."""
    text = ANSI_RE.sub("", raw)
    text = SECTION_RE.sub("", text)
    return text.replace("\r\n", "\n").replace("\r", "\n")


def tail(text: str, max_chars: int) -> str:
    """Keep the end of the log, cut at a line boundary."""
    if len(text) <= max_chars:
        return text
    cut = text[-max_chars:]
    newline = cut.find("\n")
    if 0 <= newline < 500:
        cut = cut[newline + 1 :]
    return "[... earlier output trimmed ...]\n" + cut


def redact(text: str, env: dict[str, str] | None = None) -> str:
    """Replace secrets with [REDACTED] before the log is sent anywhere."""
    env = dict(os.environ) if env is None else env
    for name, value in env.items():
        if SECRET_ENV_NAME.search(name) and value and len(value) >= 8:
            text = text.replace(value, "[REDACTED]")
    for pattern in SECRET_PATTERNS:
        if pattern.groups:
            text = pattern.sub(lambda m: m.group(1) + "[REDACTED]", text)
        else:
            text = pattern.sub("[REDACTED]", text)
    return text


def build_prompt(jobs: list[FailedJob]) -> str:
    parts = [
        "These GitLab CI jobs failed. For each job, explain the most likely root cause, "
        "quote the 1-3 log lines that show it, and suggest a concrete fix. "
        "If the logs are not enough to be sure, say so and say what to check. "
        "Answer in short markdown, one section per job, at most 200 words in total per job.",
    ]
    for job in jobs:
        parts.append(f"\n## Job `{job.name}` (stage: {job.stage})\n```\n{job.log}\n```")
    return "\n".join(parts)


def format_note(summary: str, jobs: list[FailedJob]) -> str:
    links = ", ".join(f"[{j.name}]({j.web_url})" for j in jobs)
    return f"{NOTE_HEADER}\n\nFailed jobs: {links}\n\n{summary.strip()}\n\n{DISCLAIMER}\n"


# ------------------------------------------------------------- API clients


class GitLab:
    def __init__(self, api_url: str, project_id: str, token: str, session: requests.Session | None = None):
        self.base = f"{api_url}/projects/{project_id}"
        self.http = session or requests.Session()
        self.http.headers["PRIVATE-TOKEN"] = token

    def failed_jobs(self, pipeline_id: str) -> list[FailedJob]:
        resp = self.http.get(
            f"{self.base}/pipelines/{pipeline_id}/jobs",
            params={"scope[]": "failed", "per_page": 100},
            timeout=30,
        )
        resp.raise_for_status()
        return [
            FailedJob(id=j["id"], name=j["name"], stage=j["stage"], web_url=j["web_url"])
            for j in resp.json()
            if not j.get("allow_failure")
        ]

    def job_log(self, job_id: int) -> str:
        resp = self.http.get(f"{self.base}/jobs/{job_id}/trace", timeout=60)
        resp.raise_for_status()
        return resp.text

    def comment_on_mr(self, mr_iid: str, body: str) -> None:
        resp = self.http.post(f"{self.base}/merge_requests/{mr_iid}/notes", json={"body": body}, timeout=30)
        resp.raise_for_status()


def ask_llm(prompt: str, api_key: str, model: str, session: requests.Session | None = None) -> str:
    http = session or requests.Session()
    resp = http.post(
        ANTHROPIC_URL,
        headers={"x-api-key": api_key, "anthropic-version": "2023-06-01", "content-type": "application/json"},
        json={
            "model": model,
            "max_tokens": 1500,
            "system": "You are a senior CI/CD engineer helping developers fix failed pipelines quickly.",
            "messages": [{"role": "user", "content": prompt}],
        },
        timeout=120,
    )
    resp.raise_for_status()
    blocks = resp.json().get("content", [])
    return "\n".join(b.get("text", "") for b in blocks if b.get("type") == "text").strip()


# -------------------------------------------------------------------- main


def run(env: dict[str, str], gitlab: GitLab | None = None, llm_session: requests.Session | None = None) -> int:
    gitlab = gitlab or GitLab(env["CI_API_V4_URL"], env["CI_PROJECT_ID"], env["GITLAB_API_TOKEN"])
    max_chars = int(env.get("MAX_LOG_CHARS", "8000"))

    jobs = gitlab.failed_jobs(env["CI_PIPELINE_ID"])
    if not jobs:
        print("No failed jobs (or only allowed failures). Nothing to explain.")
        return 0

    for job in jobs:
        job.log = redact(tail(clean_log(gitlab.job_log(job.id)), max_chars), env)

    prompt = build_prompt(jobs)
    api_key = env.get("ANTHROPIC_API_KEY")
    if not api_key:
        print("ANTHROPIC_API_KEY not set: dry run, this is the prompt that would be sent:\n")
        print(prompt)
        return 0

    summary = ask_llm(prompt, api_key, env.get("AI_MODEL", DEFAULT_MODEL), llm_session)
    note = format_note(summary, jobs)

    with open(REPORT_FILE, "w", encoding="utf-8") as fh:
        fh.write(note)
    print(note)

    mr_iid = env.get("CI_MERGE_REQUEST_IID")
    if mr_iid:
        gitlab.comment_on_mr(mr_iid, note)
        print(f"Posted summary on MR !{mr_iid}")
    return 0


if __name__ == "__main__":
    sys.exit(run(dict(os.environ)))
